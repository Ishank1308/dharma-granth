/**
 * Writes lib/verse-page-subset.generated.ts: for scriptures too long for a page per verse, the verses that get one.
 *
 * The Ramcharitmanas has about 6,200 chaupais, dohas and chhands, the Valmiki Ramayana about 23,600 ślokas. A page
 * (and share image) for each would take the static export past Cloudflare Pages' 20,000-file limit, so only a verse
 * with a Hindi or English meaning gets a page; the rest are read on their kanda's chapter pages. Run by `npm run search:core`, before the search index,
 * which links to verse pages.
 */
import fs from 'node:fs';
import path from 'node:path';

const MEANING_ONLY = ['ramcharitmanas', 'ramayana'];

const root = process.cwd();
const out: Record<string, string[]> = {};
for (const id of MEANING_ONLY) {
  const file = path.join(root, 'public', 'data', 'scriptures-full', `${id}.json`);
  const data = JSON.parse(fs.readFileSync(file, 'utf8')) as {
    chapters: Array<{ number: number; verses: Array<{ number: number | string; hindi?: string; translation?: string }> }>;
  };
  out[id] = data.chapters.flatMap((ch) =>
    ch.verses.filter((v) => (v.hindi ?? '').trim() || (v.translation ?? '').trim()).map((v) => `${ch.number}:${v.number}`),
  );
}

const body =
  '// Generated by scripts/build-verse-page-subset.ts from public/data/scriptures-full. Do not edit.\n' +
  '/** "chapter:verse" keys of the only verses that get a page, for the scriptures listed. */\n' +
  `export const VERSE_PAGE_SUBSET: Record<string, string[]> = ${JSON.stringify(out)};\n`;
const target = path.join(root, 'lib', 'verse-page-subset.generated.ts');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body) fs.writeFileSync(target, body);
console.log(`verse-page subset: ${Object.entries(out).map(([id, keys]) => `${id} ${keys.length}`).join(', ')}`);
