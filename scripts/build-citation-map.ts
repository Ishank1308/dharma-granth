/**
 * Writes lib/citation-map.generated.ts: for each text in lib/citation-schemes.ts, the verse labels
 * each library chapter holds, in the smallest form that is still exact:
 *   n               labels are 1..n
 *   ["p", n]        labels are p.1..p.n (Chandogya "6.8.1".."6.8.16")
 *   ["a", "b", …]   anything else, listed in full
 * Run by `npm run search:core`. The search reference jump reads it to offer only real verses.
 */
import fs from 'node:fs';
import path from 'node:path';
import { CITATION_SCHEMES } from '../lib/citation-schemes';

type Entry = number | [string, number] | string[];

const root = process.cwd();
const out: Record<string, Record<string, Entry>> = {};

for (const { id } of CITATION_SCHEMES) {
  const file = path.join(root, 'public', 'data', 'scriptures-full', `${id}.json`);
  if (!fs.existsSync(file)) throw new Error(`build-citation-map: ${id} is not in the library`);
  const data = JSON.parse(fs.readFileSync(file, 'utf8')) as { chapters?: unknown };
  const chapters = (Array.isArray(data.chapters) ? data.chapters : Object.values(data.chapters ?? {})) as Array<{
    id?: number | string;
    number?: number | string;
    verses?: Array<{ number?: number | string }>;
  }>;
  const map: Record<string, Entry> = {};
  for (const ch of chapters) {
    const chapterId = String(ch.id ?? ch.number);
    const labels = [...new Set((ch.verses ?? []).map((v) => String(v.number ?? '').trim()).filter(Boolean))];
    if (labels.length === 0) continue;
    const prefix = labels[0].match(/^(.*)\.\d+$/)?.[1];
    if (labels.every((l, i) => l === String(i + 1))) map[chapterId] = labels.length;
    else if (prefix && labels.every((l, i) => l === `${prefix}.${i + 1}`)) map[chapterId] = [prefix, labels.length];
    else map[chapterId] = labels;
  }
  out[id] = map;
}

const body = `// Generated by scripts/build-citation-map.ts from public/data/scriptures-full. Do not edit.
export type CitationChapterEntry = number | [string, number] | string[];

export const CITATION_MAP: Record<string, Record<string, CitationChapterEntry>> = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(root, 'lib', 'citation-map.generated.ts'), body);
console.log(`citation map: ${Object.keys(out).length} texts, ${(body.length / 1024).toFixed(1)} KB`);
