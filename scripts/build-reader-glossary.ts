/**
 * Writes lib/reader-glossary.generated.ts: the few fields of the dictionary, life topics and concept
 * graph that the verse reader needs on the client (glossary tooltips and keyword links). The full
 * data files stay on the server, so a chapter page does not download every definition, verse list
 * and cross-tradition note to underline a handful of words.
 * Run by `npm run search:core`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { dictionary, termCategories } from '../data/dictionary';
import { topics } from '../data/topics';
import { concepts } from '../data/concepts';

const categoryLabel = new Map(termCategories.map((c) => [c.key, c.label]));

const glossary = dictionary.map((d) => ({
  id: d.id,
  term: d.term,
  sanskrit: d.sanskrit,
  transliteration: d.transliteration,
  category: d.category,
  categoryLabel: categoryLabel.get(d.category) ?? '',
  shortDef: d.shortDef,
  etymology: d.etymology,
}));
const topicTitles = topics.map((t) => ({ id: t.id, title: t.title }));
const conceptNames = concepts.map((c) => ({ id: c.id, label: c.label, sanskrit: c.sanskrit, transliteration: c.transliteration }));

const body = `// Generated by scripts/build-reader-glossary.ts from data/dictionary.ts, data/topics.ts and data/concepts.ts. Do not edit.
export interface ReaderGlossaryTerm {
  id: string;
  term: string;
  sanskrit: string;
  transliteration: string;
  category: string;
  categoryLabel: string;
  shortDef: string;
  etymology: string;
}

export const READER_GLOSSARY: ReaderGlossaryTerm[] = ${JSON.stringify(glossary)};

export const READER_TOPICS: { id: string; title: string }[] = ${JSON.stringify(topicTitles)};

export const READER_CONCEPTS: { id: string; label: string; sanskrit: string; transliteration: string }[] = ${JSON.stringify(conceptNames)};
`;
fs.writeFileSync(path.join(process.cwd(), 'lib', 'reader-glossary.generated.ts'), body);
console.log(`reader glossary: ${glossary.length} terms, ${topicTitles.length} topics, ${conceptNames.length} concepts, ${(body.length / 1024).toFixed(1)} KB`);
