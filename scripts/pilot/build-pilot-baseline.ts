/**
 * Builds the Phase 2 pilot baseline and the selection report. Read-only with respect to scripture data.
 *
 *   npx tsx scripts/pilot/build-pilot-baseline.ts
 *
 * Writes data/pilot/pilot-baseline.json (protected-field snapshot, SHA-256 per unit) and
 * docs/pilot/pilot-selection-report.md. If a baseline already exists and any protected hash differs, it stops:
 * a canonical change is never accepted automatically. Pass --accept-canonical-change only after a person has
 * reviewed the difference.
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, ambiguityReason, loadUnit, sha256, type LayerState, type PilotUnit, type ProtectedFields } from './lib';

const SET = path.join(ROOT, 'data/pilot/pilot-set.json');
const BASELINE = path.join(ROOT, 'data/pilot/pilot-baseline.json');
const REPORT = path.join(ROOT, 'docs/pilot/pilot-selection-report.md');
const accept = process.argv.includes('--accept-canonical-change');

const GROUPS: Record<string, string> = {
  A: 'Bhagavad Gita',
  B: 'Principal Upanishads',
  C: 'Yoga Sutras',
  D: 'Ashtavakra Gita',
  E: 'Shri Ramcharitmanas',
  F: 'Purana (Vishnu Purana)',
  G: 'Devotional and hymnic texts',
};

interface BaselineUnit {
  id: string;
  reference: string;
  protected: ProtectedFields | null;
  sha256: string | null;
  baselineStatus: 'clear' | 'review-only';
  reviewOnlyReason: string | null;
}

const set = JSON.parse(fs.readFileSync(SET, 'utf8')) as { units: PilotUnit[] };
const rows: { u: PilotUnit; b: BaselineUnit; layers: LayerState | null; same: number }[] = [];

for (const u of set.units) {
  const loaded = loadUnit(u);
  const reason = ambiguityReason(u, loaded);
  rows.push({
    u,
    b: {
      id: u.id,
      reference: u.reference,
      protected: loaded.protectedFields,
      sha256: loaded.protectedFields ? sha256(loaded.protectedFields) : null,
      baselineStatus: reason ? 'review-only' : 'clear',
      reviewOnlyReason: reason,
    },
    layers: loaded.layers,
    same: loaded.sameSanskritElsewhere,
  });
}

// Never overwrite a canonical hash silently.
if (fs.existsSync(BASELINE) && !accept) {
  const old = JSON.parse(fs.readFileSync(BASELINE, 'utf8')) as { units: BaselineUnit[] };
  const oldById = new Map(old.units.map((x) => [x.id, x]));
  const changed = rows.filter((r) => oldById.get(r.b.id) && oldById.get(r.b.id)!.sha256 !== r.b.sha256).map((r) => r.b.id);
  if (changed.length) {
    console.error(`Protected canonical fields changed for: ${changed.join(', ')}. Review the difference, then re-run with --accept-canonical-change.`);
    process.exit(1);
  }
}

fs.writeFileSync(
  BASELINE,
  JSON.stringify(
    {
      version: 1,
      note: 'SHA-256 over each unit\'s protected fields (scriptureId, chapter, chapter title, verse, reference, original text, IAST, source citation). Generated by scripts/pilot/build-pilot-baseline.ts; checked by scripts/pilot/check-pilot-canonical.ts.',
      units: rows.map((r) => r.b),
    },
    null,
    2,
  ) + '\n',
);

// ── Report ──────────────────────────────────────────────────────────────────
const arthaText = (l: LayerState | null) => {
  if (!l) return 'unknown';
  if (!l.artha.hindi && !l.artha.english) return l.other.wordMeaning ? 'missing (word glosses only)' : 'missing';
  if (l.artha.hindi && !l.artha.english && l.other.attribution) return `Hindi literal meaning present, English missing (${l.artha.hindiLength}c; from the commentary record)`;
  const parts = [l.artha.hindi ? `Hindi ${l.artha.hindiLength}c` : 'no Hindi', l.artha.english ? `English ${l.artha.englishLength}c` : 'no English'];
  return `present, unreviewed (${parts.join(', ')})`;
};
const vyakText = (l: LayerState | null) => {
  if (!l) return 'unknown';
  if (l.vyakhya.hiddenAtPublish) return 'repeated template text, hidden at publish';
  if (!l.vyakhya.present) return 'missing';
  if (l.vyakhya.wordGlossOnly) return `word gloss, not exposition (${l.vyakhya.length}c)`;
  const attr = l.other.attribution ? `; attributed to ${l.other.attribution}` : '; no attribution stored';
  return `${l.vyakhya.length < 150 ? 'short note' : 'present'}, unreviewed (${l.vyakhya.length}c, ${l.vyakhya.language}${attr})`;
};
const vigText = (l: LayerState | null) => {
  if (!l) return 'unknown';
  if (l.vigyana.hiddenAtPublish) return 'repeated template text, hidden at publish';
  if (!l.vigyana.present) return 'missing';
  if (l.vigyana.startsWithHindiMeaning || l.vigyana.endsWithRepeatedSentence)
    return `boilerplate: ${l.vigyana.startsWithHindiMeaning ? 'copy of the Hindi meaning' : ''}${l.vigyana.startsWithHindiMeaning && l.vigyana.endsWithRepeatedSentence ? ' + ' : ''}${l.vigyana.endsWithRepeatedSentence ? 'generic sentence repeated across the text' : ''}; not a responsible perspective`;
  return `present, unreviewed (${l.vigyana.length}c)`;
};
const sourceText = (r: (typeof rows)[number]) => {
  if (r.u.source === 'ashtavakra') return `original and commentary in data/ashtavakra; commentator recorded: ${r.layers?.other.attribution ?? 'n/a'}`;
  return r.b.protected?.sourceCitation ? 'text source recorded in the data (repository and fetch date); translation and note attribution not recorded' : 'text source not recorded; translation and note attribution not recorded';
};

const md: string[] = [];
const count = (f: (r: (typeof rows)[number]) => boolean) => rows.filter(f).length;
md.push('# Pilot selection report (Phase 2)', '');
md.push('Generated by `scripts/pilot/build-pilot-baseline.ts` from the stored data. **No scripture or editorial field was changed.** Layer states below are measured from the files; the words "present, unreviewed" mean text exists but no review record exists anywhere in the data.', '');
md.push(`**${rows.length} units proposed** across ${Object.keys(GROUPS).length} groups. **${count((r) => r.b.baselineStatus === 'clear')} have a clear canonical baseline** and can enter editorial drafting once approved; **${count((r) => r.b.baselineStatus === 'review-only')} are review-only** because their stored canonical record is ambiguous.`, '');

md.push('## What the stored data shows', '');
const vigRows = rows.filter((r) => r.layers?.vigyana.present);
const boiler = vigRows.filter((r) => r.layers!.vigyana.startsWithHindiMeaning || r.layers!.vigyana.endsWithRepeatedSentence);
const otherVig = vigRows.filter((r) => !boiler.includes(r));
const upan = rows.filter((r) => r.u.group === 'B');
const upanGloss = upan.filter((r) => r.layers?.vyakhya.wordGlossOnly);
const noArtha = rows.filter((r) => r.layers && !r.layers.artha.hindi && !r.layers.artha.english);
md.push(
  `- **Vigyana:** ${vigRows.length} of ${rows.length} units have one. ${boiler.length} of those are boilerplate: the Hindi meaning copied, then a generic sentence that repeats across the text. That is not a responsible modern perspective. The other ${otherVig.length} (${otherVig.map((r) => r.u.reference).join('; ') || 'none'}) needs a human read; see its observation.`,
  `- **Vyakhya:** in ${upanGloss.length} of ${upan.length} Upanishad units the stored explanation is a word-by-word gloss, not an exposition.`,
  `- **No Artha at all:** ${noArtha.length} units (${noArtha.map((r) => r.u.reference).join('; ')}) have the original text only.`,
  '- **Misaligned or damaged meanings in the Vishnu Purana units:** the stored Hindi or English does not render the verse in all three units (a Hindi about different content, OCR-damaged English, truncated Hindi). This is a data fault, not a style problem, and it may affect many other Purana verses; audit before any scale-up.',
  '- **Ramcharitmanas records mix original text, a Hindi gloss and unrelated lines in one field.** The baseline is ambiguous, so these three units are review-only and no editing is proposed.',
  '- **Brihadaranyaka was not selected:** its stored text repeats "अहं ब्रह्मास्मि" as a whole verse in several positions (1:1, 2:4, 3:5, 4:4, 5:4); its baseline needs a separate rebuild decision.',
  '- **Traditional commentary is not stored for any unit** except the named modern Hindi commentator on the Ashtavakra source. Nothing in this pilot may be attributed to a classical commentator unless a person supplies and checks the source.',
  '',
);

for (const g of Object.keys(GROUPS)) {
  const group = rows.filter((r) => r.u.group === g);
  md.push(`## ${g}. ${GROUPS[g]} (${group.length})`, '');
  for (const r of group) {
    md.push(`### ${r.u.reference}`, '');
    md.push(`| Field | Value |`, `|---|---|`);
    md.push(`| Unit id | \`${r.u.id}\` |`);
    md.push(`| Scripture / canonical reference | ${r.u.scriptureId} / ${r.u.reference} |`);
    md.push(`| Unit type | ${r.u.unitType} |`);
    md.push(`| Reason selected | ${r.u.reason} |`);
    md.push(`| Existing Artha | ${arthaText(r.layers)} |`);
    md.push(`| Existing Vyakhya | ${vyakText(r.layers)} |`);
    md.push(`| Existing Vigyana | ${vigText(r.layers)} |`);
    md.push(`| Source availability | ${sourceText(r)} |`);
    md.push(`| Traditional commentary | ${r.u.traditionalCommentary} |`);
    md.push(`| Main editorial risk | ${r.u.risk} |`);
    md.push(`| Required reviewer expertise | ${r.u.reviewer} |`);
    md.push(`| Canonical baseline | **${r.b.baselineStatus}**${r.b.reviewOnlyReason ? ` — ${r.b.reviewOnlyReason}` : ''} |`);
    md.push(`| Editor observation | ${r.u.observation} |`, '');
  }
}

md.push('## Limits of this report', '');
md.push(
  '- Layer states are detected from the stored fields. A human reader must still judge whether each Hindi and English meaning is faithful; only misalignments I read directly are noted as observations.',
  '- Verse references in the Puranas and Chandogya use the dataset\'s running chapter index. Edition numbering is unverified for these units.',
  '- No external source was consulted for this report. Any traditional commentary, scholarly or scientific source used later must be supplied or fetched with permission and recorded in the unit\'s provenance.',
  '',
);
md.push('## Proposed next step', '');
md.push('On approval of the set, draft the units with a clear baseline in batches of three to five, each as a proposal beside the existing text (not written to production data), with the canonical check run before and after every batch.', '');

fs.mkdirSync(path.dirname(REPORT), { recursive: true });
fs.writeFileSync(REPORT, md.join('\n'));
const clear = rows.filter((r) => r.b.baselineStatus === 'clear').length;
console.log(`pilot units: ${rows.length}, clear baseline: ${clear}, review-only: ${rows.length - clear}`);
console.log('wrote data/pilot/pilot-baseline.json and docs/pilot/pilot-selection-report.md');
