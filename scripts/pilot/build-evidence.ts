/**
 * Builds the pilot evidence documents from the stored source data and the editorial records. Read-only.
 *
 *   npx tsx scripts/pilot/build-evidence.ts
 *
 * Writes docs/pilot/pilot-before-after.md (existing and proposed text side by side, with decisions) and
 * docs/pilot/pilot-review-queue.md (canonical problems and unresolved questions for a person).
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, SOURCE_DIR, type PilotUnit } from './lib';
import type { PilotRecord } from './validate-pilot-records';

const set = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/pilot/pilot-set.json'), 'utf8')) as { units: PilotUnit[] };
const baseline = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/pilot/pilot-baseline.json'), 'utf8')) as { units: { id: string; baselineStatus: string; reviewOnlyReason: string | null }[] };
const recDir = path.join(ROOT, 'data/pilot/records');
const records = new Map<string, PilotRecord>();
for (const f of fs.readdirSync(recDir).filter((x) => x.endsWith('.json'))) {
  const r = JSON.parse(fs.readFileSync(path.join(recDir, f), 'utf8')) as PilotRecord;
  records.set(r.unitId, r);
}

interface Raw { sanskrit?: string; hindi?: string; translation?: string; explanation?: string; commentary?: string; science?: string; lifeLesson?: string; wordMeaning?: string; number?: number | string }
interface Existing { hindi: string; english: string; explanation: string; science: string; lesson: string; wordMeaning: string }

function existing(u: PilotUnit): Existing | null {
  if (u.source === 'ashtavakra') {
    const list = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/ashtavakra', `ashtavakra_prakaran_${u.chapter}.json`), 'utf8')) as { verse_number: number; bhavartha?: string }[];
    const v = list.find((x) => String(x.verse_number) === u.verse);
    if (!v) return null;
    const lit = (v.bhavartha ?? '').match(/^\s*शाब्दिक अर्थ:\s*([^\n]+)/);
    return { hindi: lit ? lit[1].trim() : '', english: '', explanation: (v.bhavartha ?? '').replace(/^\s*शाब्दिक अर्थ:[^\n]*\n*/, ''), science: '', lesson: '', wordMeaning: '' };
  }
  const mono = JSON.parse(fs.readFileSync(path.join(SOURCE_DIR, `${u.scriptureId}.json`), 'utf8')) as { chapters: { number: number; verses: Raw[] }[] };
  const v = mono.chapters.find((c) => c.number === u.chapter)?.verses.find((x) => String(x.number) === u.verse);
  if (!v) return null;
  return { hindi: v.hindi ?? '', english: v.translation ?? '', explanation: v.explanation ?? v.commentary ?? '', science: v.science ?? '', lesson: v.lifeLesson ?? '', wordMeaning: v.wordMeaning ?? '' };
}

const clip = (s: string, n = 420) => {
  const t = s.replace(/\s+/g, ' ').trim();
  return t.length > n ? `${t.slice(0, n)}…` : t || '*(none)*';
};
const quote = (s: string, n?: number) => clip(s, n).replace(/\|/g, '\\|');

const out: string[] = [];
out.push('# Pilot before and after', '');
out.push('Generated by `scripts/pilot/build-evidence.ts`. "Existing" is the text stored in the source data today; "Proposed" is the editorial draft in `data/pilot/records/`. Every proposed field is an **AI-assisted draft that no person has reviewed**; its status is `review-required`. Original text, transliteration, reference and verse number were not changed (see the canonical check). Existing text is shown clipped.', '');

const decisions: Record<string, number> = {};
for (const u of set.units) {
  const b = baseline.units.find((x) => x.id === u.id)!;
  const r = records.get(u.id);
  out.push(`## ${u.reference}`, '');
  if (!r) {
    out.push(`**No draft written.** ${b.baselineStatus === 'review-only' ? `Review-only: ${b.reviewOnlyReason}` : 'No record.'}`, '');
    decisions['send-for-review'] = (decisions['send-for-review'] ?? 0) + 1;
    continue;
  }
  const e = existing(u);
  decisions[r.arthaDecision] = (decisions[r.arthaDecision] ?? 0) + 1;
  const vig = r.vijnana.trim() ? `**revised/added** (${r.vijnanaCategory}, ${r.evidenceLevel})` : '**none written** (no honest parallel, or not applicable)';
  out.push(`Unit \`${u.id}\` · Artha decision: **${r.arthaDecision}** · Vigyana: ${vig} · confidence: **${r.confidence}** · status: **${r.reviewStatus}**`, '');
  out.push('| Field | Existing | Proposed |', '|---|---|---|');
  out.push(`| Artha (Hindi) | ${quote(e?.hindi ?? '')} | ${quote(r.artha)} |`);
  out.push(`| Artha (English) | ${quote(e?.english ?? '')} | ${quote(r.arthaEn)} |`);
  out.push(`| Vyakhya | ${quote(e?.explanation ?? '')} | ${quote(r.vyakhya, 520)} |`);
  out.push(`| Vigyana | ${quote(e?.science ?? '')} | ${r.vijnana.trim() ? quote(r.vijnana, 520) : '*(none)*'} |`);
  out.push(`| Life lesson | ${quote(e?.lesson ?? '')} | ${quote(r.lifeLesson)} |`);
  out.push('', `**Review note:** ${r.reviewNote || '*(none)*'}`, '');
}

out.push('## Decision summary', '');
out.push('| Decision | Units |', '|---|---:|');
for (const [k, v] of Object.entries(decisions).sort()) out.push(`| ${k} | ${v} |`);
out.push('', `Records written: ${records.size} of ${set.units.length} units.`, '');
fs.writeFileSync(path.join(ROOT, 'docs/pilot/pilot-before-after.md'), out.join('\n'));

// ── Review queue ────────────────────────────────────────────────────────────
const q: string[] = [];
q.push('# Pilot review queue', '');
q.push('Everything below needs a person. Nothing here was fixed silently.', '');
q.push('## Canonical problems (protected fields: not edited)', '');
q.push(
  '1. **Ramcharitmanas (3 units, review-only).** The stored `sanskrit` field mixes the original with a Hindi gloss, and `translation`, `hindi` and `wordMeaning` hold unrelated or repeated lines. No draft was written. Needs a fresh, verified source for the text.',
  '2. **Chandogya transliteration (fixed).** 565 of 628 verses carried an ITRANS or Harvard-Kyoto romanization instead of IAST. They were regenerated from the stored Devanagari with scripts/regenerate-iast.ts and the canonical manifest was re-baselined in the same commit. A reviewer should spot-check a few chapters.',
  '3. **Devi Mahatmya Devi Stuti block.** The stored record merges 22 separate stanzas under one number (labelled 5.77), and the next record, the "citirupena" stanza, is numbered 5.81 although it precedes 5.81 in the standard text. The numbering needs checking against an edition.',
  '4. **Brihadaranyaka (not selected).** "अहं ब्रह्मास्मि" is stored as a whole verse in several positions (1:1, 2:4, 3:5, 4:4, 5:4).',
  '5. **Vishnu Purana references.** The dataset uses a running chapter index and its own verse numbering; the edition numbers of the three pilot units are unverified. Hindi and English meanings in these units belonged to other verses.',
  '6. **Chandogya, Katha, Devi and Vishnu Purana chapter numbers** in the dataset are running indexes, not the texts\' own chapter numbers (the pilot labels use the text\'s own).',
  '',
);
q.push('## Unresolved scholarly questions, by unit', '');
for (const u of set.units) {
  const r = records.get(u.id);
  if (!r) continue;
  q.push(`- **${u.reference}** (confidence ${r.confidence}): ${r.reviewNote}`);
}
q.push('', '## Needed from a person before any of this is called reviewed', '');
q.push(
  '- A reader of Sanskrit and Hindi for each text to check the Artha against the original.',
  '- For the Gita 18.66, Chandogya 6.8.7, Katha 1.2.23 and Isha 1 units: a reviewer from each major tradition to confirm that the descriptions of differing readings are fair. They are given in general terms with no attribution because no commentary text is stored in the repository.',
  '- For each Vigyana written (11 units): a reader with relevant expertise to confirm it can stay, or to ask for it to be removed. None cites a source; none states a statistic.',
  '- A decision on whether the editor-draft label should stay on the page until review.',
  '',
);
fs.writeFileSync(path.join(ROOT, 'docs/pilot/pilot-review-queue.md'), q.join('\n'));
console.log(`wrote docs/pilot/pilot-before-after.md and docs/pilot/pilot-review-queue.md (${records.size} records, ${set.units.length - records.size} without a draft)`);
