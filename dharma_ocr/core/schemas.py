"""
Data Models and JSON Schema Definitions for Dharma Granth Scripture OCR Pipeline.
Compatible with Python 3.10+, Pydantic v2, and direct JSON export.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class PageQualityMetrics(BaseModel):
    """Computer vision quality metrics evaluated prior to OCR engine routing."""
    contrast: float = Field(..., description="Michelson / RMS contrast of the page [0.0 - 1.0]")
    blur_variance: float = Field(..., description="Laplacian variance of blur; values < 100 indicate blur")
    skew_angle_deg: float = Field(..., description="Detected deskew angle in degrees")
    bleed_ratio: float = Field(..., description="Estimated background bleed-through score [0.0 - 1.0]")
    quality_score: float = Field(..., description="Aggregate image quality score [0.0 - 100.0]")
    is_blurred: bool = Field(default=False)
    is_skewed: bool = Field(default=False)


class OCRResult(BaseModel):
    """Raw output from the OCR engine (Tesseract or Surya)."""
    engine_name: str = Field(..., description="'tesseract' or 'surya'")
    psm_mode: Optional[int] = Field(None, description="Tesseract Page Segmentation Mode used")
    confidence: float = Field(..., description="Average page-level confidence score [0.0 - 100.0]")
    raw_text: str = Field(..., description="Raw text generated by the engine before normalization")
    word_count: int = Field(default=0)
    processing_time_sec: float = Field(default=0.0)
    hocr: Optional[str] = Field(None, description="HOCR layout XML if available")
    bbox_words: Optional[List[Dict[str, Any]]] = Field(default=None, description="Word bounding boxes")


class ExtractedVerse(BaseModel):
    """Structured scripture verse / shloka object."""
    chapter_num: int = Field(..., description="Chapter number containing the verse")
    verse_num: int = Field(..., description="Verse / Shloka number (e.g. 1)")
    verse_range_end: Optional[int] = Field(None, description="Optional ending range for combined verses (e.g. 2 for 1-2)")
    sanskrit: str = Field(..., description="Canonical Unicode Sanskrit Devanagari verse text")
    transliteration: Optional[str] = Field(None, description="IAST Romanized transliteration")
    hindi: Optional[str] = Field(None, description="Hindi translation / Anuvada / Bhashya if present")
    translation: Optional[str] = Field(None, description="English translation if present")
    word_meaning: Optional[str] = Field(None, description="Padaccheda or word-by-word meaning")
    commentary: Optional[str] = Field(None, description="Detailed tika / commentary excerpt")
    source_page: int = Field(..., description="Original PDF page number (1-indexed)")
    confidence_score: float = Field(..., description="Verse recognition confidence [0.0 - 100.0]")
    warnings: List[str] = Field(default_factory=list)


class ExtractedChapter(BaseModel):
    """Structured chapter / section object with verse hierarchy."""
    chapter_number: int = Field(..., description="Sequential chapter number")
    title: str = Field(..., description="Chapter title (Hindi/English/Normalized)")
    title_sanskrit: Optional[str] = Field(None, description="Original Devanagari Sanskrit heading")
    hierarchy_type: str = Field(default="अध्याय", description="अध्याय, स्कन्ध, पर्व, सर्ग, काण्ड, etc.")
    page_start: int = Field(..., description="Starting page number")
    page_end: int = Field(..., description="Ending page number")
    colophon: Optional[str] = Field(None, description="Concluding colophon (पुष्पिका)")
    verses: List[ExtractedVerse] = Field(default_factory=list)


class PageRecord(BaseModel):
    """Full lifecycle tracking record for a single processed PDF page."""
    page_number: int
    source_pdf: str
    image_path: Optional[str] = None
    cleaned_image_path: Optional[str] = None
    quality_metrics: Optional[PageQualityMetrics] = None
    ocr_result: Optional[OCRResult] = None
    normalized_text: str = ""
    detected_chapter_title: Optional[str] = None
    detected_chapter_num: Optional[int] = None
    verses_on_page: List[ExtractedVerse] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)
    status: str = Field(default="pending", description="'pending', 'processed', 'failed'")
    error_message: Optional[str] = None


class OCRQualityReport(BaseModel):
    """Comprehensive statistical report on OCR accuracy, engine usage, and performance."""
    total_pages: int
    processed_pages: int
    average_confidence: float
    confidence_histogram: Dict[str, int] = Field(
        default_factory=lambda: {"90-100": 0, "75-89": 0, "50-74": 0, "below-50": 0}
    )
    low_confidence_pages: List[int] = Field(default_factory=list)
    engine_selection_distribution: Dict[str, int] = Field(
        default_factory=lambda: {"tesseract": 0, "surya": 0}
    )
    total_processing_time_sec: float
    average_speed_sec_per_page: float
    detected_chapters_count: int
    detected_verses_count: int
    estimated_text_accuracy_percent: float


class BookScriptureDocument(BaseModel):
    """
    Top-level scripture document export suitable for web readers, 
    vector search, RAG pipelines, and digital preservation archives.
    """
    schema_version: str = "2.0.0"
    title: str
    slug: str
    source_file: str
    total_pages: int
    processed_pages: int
    created_at: str
    config_summary: Dict[str, Any]
    quality_report: OCRQualityReport
    chapters: List[ExtractedChapter] = Field(default_factory=list)
    standalone_verses: List[ExtractedVerse] = Field(
        default_factory=list, 
        description="Verses detected prior to the first chapter or between sections"
    )
    unassigned_text: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Non-verse passages (introductions, prefaces, appendixes)"
    )
