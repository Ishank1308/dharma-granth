// The Ashtavakra Gita for the app: the same composed chapters the website publishes at /ashtavakra/
// (../data/ashtavakra/chapter-N.json, chapter list in chapters-meta.ts), slimmed to what the app shows.
//
// Output (git-ignored, regenerated with the rest of the content):
//   src/content/generated/ashtavakra-meta.json    the chapter list: titles, essence, palette, verse counts
//   src/content/generated/assets/content/ashtavakra/ch-N.json   one chapter: introduction, verses, closing section
//   src/content/generated/ashtavakra-loaders.android.ts   reads a chapter from the APK assets when it opens
//   src/content/generated/ashtavakra-loaders.ts   the same as lazy require()s, for web and iOS
//
// Like the other books, the chapters ship as compressed APK assets on Android, outside the Hermes bundle
// (see build-content.mjs); only the small chapter list is in the JS bundle.
//
// The book's commentary is reproduced in original words upstream (CLAUDE.md); this only copies fields.
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { readJson } from './content-lib.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(HERE, '../../data/ashtavakra');
const OUT = resolve(HERE, '../src/content/generated');
const DIR = join(OUT, 'assets/content/ashtavakra');
const META = join(OUT, 'ashtavakra-meta.json');

const VERSE_FIELDS = [
  'verseNumber',
  'speaker',
  'sanskrit',
  'iast',
  'padaccheda',
  'wordMeanings',
  'literalHindiMeaning',
  'englishTranslation',
  'bookBasedHindiExplanation',
  'simpleHindiExplanation',
  'simpleEnglishExplanation',
  'philosophicalExplanationHindi',
  'analogyHindi',
  'commonMisunderstandingHindi',
  'modernExampleHindi',
  'messageForTodayHindi',
  'practicalApplicationHindi',
  'reflectionQuestionHindi',
  'shortPracticeHindi',
  'oneLineSummaryHindi',
  'verificationStatus',
];

const pick = (obj, keys) => {
  const out = {};
  for (const k of keys) {
    const v = obj?.[k];
    if (v == null || v === '' || (Array.isArray(v) && v.length === 0)) continue;
    out[k] = typeof v === 'string' ? v.trim() : v;
  }
  return out;
};

export async function buildAshtavakra() {
  // The layout before the chapters moved to assets/; clear it so Metro never bundles stale copies.
  rmSync(join(OUT, 'ashtavakra'), { recursive: true, force: true });
  rmSync(DIR, { recursive: true, force: true });
  rmSync(META, { force: true });
  if (!existsSync(SRC)) {
    console.warn('[content] data/ashtavakra not found; the app ships without the Ashtavakra Gita.');
    writeLoaders([]);
    return;
  }
  mkdirSync(DIR, { recursive: true });
  const { CHAPTERS } = await import(pathToFileURL(join(SRC, 'chapters-meta.ts')).href);
  const published = [];
  const meta = [];
  let verses = 0;
  for (const ch of CHAPTERS) {
    const path = join(SRC, `chapter-${ch.number}.json`);
    const data = existsSync(path) ? readJson(path) : null;
    const list = (data?.verses ?? []).map((v) => pick(v, VERSE_FIELDS)).filter((v) => v.sanskrit);
    meta.push({
      number: ch.number,
      bookTitle: ch.bookTitle,
      title: ch.title,
      essence: ch.essence,
      symbol: ch.symbol,
      palette: ch.palette,
      verseCount: list.length,
      summary: data?.hero?.oneLineSummary,
      readingTime: data?.hero?.estimatedReadingTime,
    });
    if (!list.length) continue;
    const chapter = {
      number: ch.number,
      titleBook: data.chapterTitleBook,
      title: data.chapterTitleEditorial || ch.title,
      speakers: data.speakers,
      closingLine: data.closingLine,
      hero: pick(data.hero, ['oneLineSummary', 'keySanskritTerms', 'mainTopics', 'estimatedReadingTime']),
      introduction: data.introduction,
      centralQuestion: data.centralQuestion,
      mainTeaching: data.mainTeaching,
      concepts: data.concepts ?? [],
      beforeYouRead: data.beforeYouRead ?? [],
      verses: list,
      end: pick(data.end, ['simpleSummary', 'fiveTeachings', 'misunderstandings', 'reflectionQuestions', 'fiveMinutePractice', 'faqs']),
      source: pick(data.source, ['title', 'publisher', 'rightsNote']),
    };
    writeFileSync(join(DIR, `ch-${ch.number}.json`), JSON.stringify(chapter));
    published.push(ch.number);
    verses += list.length;
  }
  writeFileSync(META, JSON.stringify(meta));
  writeLoaders(published);
  console.log(`[content] Ashtavakra Gita: ${published.length} chapters, ${verses} verses`);
}

function writeLoaders(numbers) {
  const head = (lines) =>
    [
      '// Generated by scripts/build-ashtavakra.mjs. Do not edit.',
      ...lines,
      "import type { AshtavakraChapter, AshtavakraChapterMeta } from '../ashtavakra-types';",
      '',
      numbers.length
        ? "export const ASHTAVAKRA_META = require('./ashtavakra-meta.json') as AshtavakraChapterMeta[];"
        : 'export const ASHTAVAKRA_META: AshtavakraChapterMeta[] = [];',
      '',
      'export const ASHTAVAKRA_LOADERS: Record<number, () => AshtavakraChapter> = {',
    ];
  writeFileSync(
    join(OUT, 'ashtavakra-loaders.ts'),
    [
      ...head(['// Web and iOS: lazy require()s. Android uses ashtavakra-loaders.android.ts (APK assets) instead.']),
      ...numbers.map((n) => `  ${n}: () => require('./assets/content/ashtavakra/ch-${n}.json') as AshtavakraChapter,`),
      '};',
      '',
    ].join('\n'),
  );
  writeFileSync(
    join(OUT, 'ashtavakra-loaders.android.ts'),
    [
      ...head(["import { readBundledJson } from '../bundled-assets';"]),
      ...numbers.map((n) => `  ${n}: () => readBundledJson<AshtavakraChapter>('ashtavakra/ch-${n}.json'),`),
      '};',
      '',
    ].join('\n'),
  );
}

if (import.meta.url === `file://${process.argv[1]}`) await buildAshtavakra();
