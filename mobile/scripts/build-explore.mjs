// Copy the website's Panchang, festival and mantra data into the app, so the Explore tab shows exactly what
// dharmagranth.dev shows and the two never drift apart.
//
//   node scripts/build-explore.mjs      (also run by build-content.mjs, on every build)
//
// Sources (the website's own files, unchanged):
//   ../lib/panchang.ts               Panchang calculation, cities and the meaning of every tithi, nakshatra, yoga…
//   ../data/festivals.ts             festival pages (meaning, practices, chants, regional customs)
//   ../data/festival-dates.ts        dated festival calendar
//   ../data/mantras.ts               Vedic mantras, शान्ति पाठ and stotras with पदच्छेद and भावार्थ
//   ../data/rituals.ts               temple and household rituals (/rituals/)
//   ../data/upakarma-data.ts         the Upakarma guide (/rituals/upakarma/)
//   ../app/panchang/{ekadashi,purnima,amavasya,pradosh}/page.tsx   the vrat date tables
//   ../app/panchang/{calendar,tithis,nakshatras,yogas,karanas,varas}/page.tsx   those pages' questions and answers
//
// Output (git-ignored): src/content/generated/explore/*.ts
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const MOBILE = resolve(HERE, '..');
const ROOT = resolve(MOBILE, '..');
const OUT = join(MOBILE, 'src/content/generated/explore');

/** The files copied as they are: none of them imports anything. */
const COPIES = [
  ['lib/panchang.ts', 'panchang.ts'],
  ['data/festivals.ts', 'festivals.ts'],
  ['data/festival-dates.ts', 'festival-dates.ts'],
  ['data/mantras.ts', 'mantras.ts'],
  ['data/rituals.ts', 'rituals.ts'],
  ['data/upakarma-data.ts', 'upakarma.ts'],
];

/** Pages whose `const FAQS = [ { q, a }, … ];` the app shows under the same page. */
export const FAQ_PAGES = ['calendar', 'tithis', 'nakshatras', 'yogas', 'karanas', 'varas'];

/** Vrat tables live inside the website's pages as `const NAME: VrataDateItem[] = [ … ];`. */
const VRATS = [
  ['ekadashi', 'EKADASHI_DATES'],
  ['purnima', 'PURNIMA_DATES'],
  ['amavasya', 'AMAVASYA_DATES'],
  ['pradosh', 'PRADOSH_DATES'],
];

export function extractVrataTable(source, name) {
  const start = source.indexOf(`const ${name}: VrataDateItem[] = [`);
  if (start < 0) throw new Error(`${name} not found`);
  const open = source.indexOf('[', source.indexOf('=', start));
  const close = source.indexOf('\n];', open);
  if (close < 0) throw new Error(`${name} has no closing bracket`);
  return source.slice(open, close + 2);
}

/** The `const FAQS = [ … ];` array literal of a website page (plain { q, a } string pairs). */
export function extractFaqs(source) {
  const start = source.indexOf('const FAQS = [');
  if (start < 0) throw new Error('FAQS not found');
  const open = source.indexOf('[', start);
  const close = source.indexOf('\n];', open);
  if (close < 0) throw new Error('FAQS has no closing bracket');
  return source.slice(open, close + 2);
}

export function buildExplore() {
  mkdirSync(OUT, { recursive: true });
  for (const [from, to] of COPIES) {
    const src = join(ROOT, from);
    if (!existsSync(src)) throw new Error(`[explore] ${from} not found. Run this from a full checkout of the repo.`);
    // The website's own header comment stays; this line says where the copy came from.
    const body = readFileSync(src, 'utf8').replace(/\r\n/g, '\n');
    writeFileSync(join(OUT, to), `// Generated by scripts/build-explore.mjs from ${from}. Edit that file, not this one.\n${body}`);
  }

  const tables = VRATS.map(([page, name]) => {
    const source = readFileSync(join(ROOT, `app/panchang/${page}/page.tsx`), 'utf8').replace(/\r\n/g, '\n');
    return `export const ${name}: VrataDateItem[] = ${extractVrataTable(source, name)};`;
  });
  writeFileSync(
    join(OUT, 'vrata-dates.ts'),
    [
      '// Generated by scripts/build-explore.mjs from app/panchang/*/page.tsx. Edit those pages, not this file.',
      'export interface VrataDateItem {',
      '  name: string;',
      '  month: string;',
      '  date: string;',
      '  dateEn: string;',
      '  highlight?: boolean;',
      '  paksha?: string;',
      '  tithiTime?: string;',
      '}',
      '',
      ...tables,
      '',
    ].join('\n'),
  );
  const faqs = FAQ_PAGES.map((page) => {
    const source = readFileSync(join(ROOT, `app/panchang/${page}/page.tsx`), 'utf8').replace(/\r\n/g, '\n');
    return `  ${page}: ${extractFaqs(source).replace(/\n/g, '\n  ')},`;
  });
  writeFileSync(
    join(OUT, 'faqs.ts'),
    [
      '// Generated by scripts/build-explore.mjs from app/panchang/*/page.tsx. Edit those pages, not this file.',
      'export interface PageFaq {',
      '  q: string;',
      '  a: string;',
      '}',
      '',
      'export const PAGE_FAQS: Record<string, PageFaq[]> = {',
      ...faqs,
      '};',
      '',
    ].join('\n'),
  );
  console.log(`[explore] ${COPIES.length} website files, ${VRATS.length} vrat tables and ${FAQ_PAGES.length} FAQ lists → src/content/generated/explore/`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) buildExplore();
