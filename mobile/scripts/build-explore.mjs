// Copy the website's Panchang, festival and mantra data into the app, so the Explore tab shows exactly what
// dharmagranth.dev shows and the two never drift apart.
//
//   node scripts/build-explore.mjs      (also run by build-content.mjs, on every build)
//
// Sources (the website's own files, unchanged):
//   ../lib/panchang.ts               Panchang calculation, cities and the meaning of every tithi, nakshatra, yoga…
//   ../data/festivals.ts             festival pages (meaning, practices, chants, regional customs)
//   ../data/festival-dates.ts        dated festival calendar
//   ../data/mantras.ts               Vedic mantras, शान्ति पाठ and stotras with पदच्छेद and भावार्थ
//   ../data/ekadashi-dates.ts        Ekadashi dates (also the Android app's Ekadashi reminders)
//   ../app/panchang/{purnima,amavasya,pradosh}/page.tsx   the other vrat date tables
//
// Output (git-ignored): src/content/generated/explore/*.ts
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const MOBILE = resolve(HERE, '..');
const ROOT = resolve(MOBILE, '..');
const OUT = join(MOBILE, 'src/content/generated/explore');

/** The files copied as they are: none of them imports anything. */
const COPIES = [
  ['lib/panchang.ts', 'panchang.ts'],
  ['data/festivals.ts', 'festivals.ts'],
  ['data/festival-dates.ts', 'festival-dates.ts'],
  ['data/mantras.ts', 'mantras.ts'],
];

/**
 * Vrat tables live inside the website's pages as `const NAME: VrataDateItem[] = [ … ];`, or in a data file of
 * their own (`export const NAME: SomeType[] = [ … ];`). The first source that exists is read.
 */
const VRATS = [
  [['data/ekadashi-dates.ts', 'app/panchang/ekadashi/page.tsx'], 'EKADASHI_DATES'],
  [['app/panchang/purnima/page.tsx'], 'PURNIMA_DATES'],
  [['app/panchang/amavasya/page.tsx'], 'AMAVASYA_DATES'],
  [['app/panchang/pradosh/page.tsx'], 'PRADOSH_DATES'],
];

export function extractVrataTable(source, name) {
  const found = new RegExp(`const ${name}: \\w+\\[\\] = \\[`).exec(source);
  if (!found) throw new Error(`${name} not found`);
  const start = found.index;
  const open = source.indexOf('[', source.indexOf('=', start));
  const close = source.indexOf('\n];', open);
  if (close < 0) throw new Error(`${name} has no closing bracket`);
  return source.slice(open, close + 2);
}

export function buildExplore() {
  mkdirSync(OUT, { recursive: true });
  for (const [from, to] of COPIES) {
    const src = join(ROOT, from);
    if (!existsSync(src)) throw new Error(`[explore] ${from} not found. Run this from a full checkout of the repo.`);
    // The website's own header comment stays; this line says where the copy came from.
    const body = readFileSync(src, 'utf8').replace(/\r\n/g, '\n');
    writeFileSync(join(OUT, to), `// Generated by scripts/build-explore.mjs from ${from}. Edit that file, not this one.\n${body}`);
  }

  const tables = VRATS.map(([sources, name]) => {
    const from = sources.find((f) => existsSync(join(ROOT, f)));
    if (!from) throw new Error(`[explore] none of ${sources.join(', ')} found. Run this from a full checkout of the repo.`);
    const source = readFileSync(join(ROOT, from), 'utf8').replace(/\r\n/g, '\n');
    return `export const ${name}: VrataDateItem[] = ${extractVrataTable(source, name)};`;
  });
  writeFileSync(
    join(OUT, 'vrata-dates.ts'),
    [
      '// Generated by scripts/build-explore.mjs from data/ekadashi-dates.ts and app/panchang/*/page.tsx. Edit those, not this file.',
      'export interface VrataDateItem {',
      '  name: string;',
      '  month: string;',
      '  date: string;',
      '  dateEn: string;',
      '  highlight?: boolean;',
      '  paksha?: string;',
      '  tithiTime?: string;',
      '}',
      '',
      ...tables,
      '',
    ].join('\n'),
  );
  console.log(`[explore] ${COPIES.length} website files and ${VRATS.length} vrat tables → src/content/generated/explore/`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) buildExplore();
