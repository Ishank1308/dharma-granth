// Build the offline verse search index from the bundled books.
//
//   node scripts/build-search-index.mjs     (also runs at the end of scripts/build-content.mjs)
//
// Reads  src/content/generated/catalog.json + assets/content/books/<id>/ch-N.json
// Writes src/content/generated/assets/content/search/<id>.json   one compact corpus per bundled book
//        src/content/generated/search-loaders.android.ts  reads a corpus from the APK assets on first search
//        src/content/generated/search-loaders.ts          lazy require() map for web and iOS
// Nothing loads until the first search.
//
// Each corpus has one line per verse, in reading order:
//   d  Sanskrit | Hindi, in the one-byte index alphabet (src/lib/verse-search.ts)
//   t  transliteration, folded for matching only
//   e  English translation, ASCII, case kept for snippets
//   c  [chapter number, verse count] pairs, to map a line back to its verse
//   n  verse numbers, one per line
// Commentary and word meanings stay out, to keep the bundle small.
//
// Needs Node 22.18+ (or 23.6+), which runs the shared TypeScript fold module directly.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Buffer } from 'node:buffer';

const HERE = dirname(fileURLToPath(import.meta.url));
const MOBILE = resolve(HERE, '..');
const OUT = join(MOBILE, 'src/content/generated');

export async function buildSearchIndex() {
  const fold = await import(pathToFileURL(join(MOBILE, 'src/lib/verse-search.ts')).href);
  const { devToIndex, englishToIndex, foldLatin, FIELD_SEP } = fold;

  const catalog = JSON.parse(readFileSync(join(OUT, 'catalog.json'), 'utf8'));
  const content = join(OUT, 'assets/content');
  const dir = join(content, 'search');
  // Layout before the index moved to assets/; clear it so Metro never bundles stale copies.
  rmSync(join(OUT, 'search'), { recursive: true, force: true });
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });

  const flat = (s) => (s ?? '').replace(/\s+/g, ' ');
  const ids = [];
  let bytes = 0;
  let verses = 0;

  for (const entry of catalog) {
    const dirOf = join(content, 'books', entry.id);
    if (!entry.bundled || !existsSync(dirOf)) continue;
    const book = { chapters: [] };
    for (const ch of entry.chapters) {
      const p = join(dirOf, `ch-${ch.number}.json`);
      if (existsSync(p)) book.chapters.push(JSON.parse(readFileSync(p, 'utf8')));
    }
    const d = [];
    const t = [];
    const e = [];
    const n = [];
    const c = [];
    for (const ch of book.chapters) {
      c.push([ch.number, ch.verses.length]);
      for (const v of ch.verses) {
        d.push(devToIndex(flat(v.sanskrit)) + FIELD_SEP + devToIndex(flat(v.hindi)));
        t.push(foldLatin(flat(v.transliteration)));
        e.push(englishToIndex(flat(v.translation)));
        n.push(String(v.number).replace(/\n/g, ' '));
      }
    }
    verses += n.length;
    const json = JSON.stringify({ d: d.join('\n'), t: t.join('\n'), e: e.join('\n'), c, n: n.join('\n') });
    bytes += Buffer.byteLength(json);
    writeFileSync(join(dir, `${entry.id}.json`), json);
    ids.push(entry.id);
  }

  const loaderMap = (entry) => [
    'export const SEARCH_LOADERS: Record<string, () => SearchCorpus> = {',
    ...ids.map((id) => `  ${JSON.stringify(id)}: ${entry(`search/${id}.json`)},`),
    '};',
    '',
  ];
  writeFileSync(
    join(OUT, 'search-loaders.ts'),
    [
      '// Generated by scripts/build-search-index.mjs. Do not edit.',
      '// Web and iOS: lazy require()s. Android uses search-loaders.android.ts (APK assets) instead.',
      "import type { SearchCorpus } from '../types';",
      '',
      ...loaderMap((path) => `() => require('./assets/content/${path}') as SearchCorpus`),
    ].join('\n'),
  );
  writeFileSync(
    join(OUT, 'search-loaders.android.ts'),
    [
      '// Generated by scripts/build-search-index.mjs. Do not edit.',
      "import { readBundledJson } from '../bundled-assets';",
      "import type { SearchCorpus } from '../types';",
      '',
      ...loaderMap((path) => `() => readBundledJson<SearchCorpus>(${JSON.stringify(path)})`),
    ].join('\n'),
  );
  console.log(`[search] indexed ${verses.toLocaleString('en-US')} verses in ${ids.length} books (${(bytes / 1024 / 1024).toFixed(1)} MB)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildSearchIndex();
}
