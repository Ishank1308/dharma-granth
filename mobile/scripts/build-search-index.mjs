// Build the offline verse search index from the bundled books.
//
//   node scripts/build-search-index.mjs     (also runs at the end of scripts/build-content.mjs)
//
// Reads  src/content/generated/catalog.json + books/<id>/ch-N.json
// Writes src/content/generated/search/<id>.json   one compact corpus per bundled book
//        src/content/generated/search-loaders.ts  lazy require() map, so nothing loads until the first search
//
// Each corpus has one line per verse, in reading order:
//   d  Sanskrit | Hindi, in the one-byte index alphabet (src/lib/verse-search.ts)
//   t  transliteration, folded for matching only
//   e  English translation, ASCII, case kept for snippets
//   c  [chapter number, verse count] pairs, to map a line back to its verse
//   n  verse numbers, one per line
// Commentary and word meanings stay out, to keep the bundle small.
//
// Needs Node 22.18+ (or 23.6+), which runs the shared TypeScript fold module directly.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Buffer } from 'node:buffer';

const HERE = dirname(fileURLToPath(import.meta.url));
const MOBILE = resolve(HERE, '..');
const OUT = join(MOBILE, 'src/content/generated');

export async function buildSearchIndex() {
  const fold = await import(pathToFileURL(join(MOBILE, 'src/lib/verse-search.ts')).href);
  const { verseToCorpusLine } = fold;

  const catalog = JSON.parse(readFileSync(join(OUT, 'catalog.json'), 'utf8'));
  const dir = join(OUT, 'search');
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });

  const ids = [];
  let bytes = 0;
  let verses = 0;

  for (const entry of catalog) {
    const dirOf = join(OUT, 'books', entry.id);
    if (!entry.bundled || !existsSync(dirOf)) continue;
    const book = { chapters: [] };
    for (const ch of entry.chapters) {
      const p = join(dirOf, `ch-${ch.number}.json`);
      if (existsSync(p)) book.chapters.push(JSON.parse(readFileSync(p, 'utf8')));
    }
    const d = [];
    const t = [];
    const e = [];
    const n = [];
    const c = [];
    for (const ch of book.chapters) {
      c.push([ch.number, ch.verses.length]);
      for (const v of ch.verses) {
        const line = verseToCorpusLine(v);
        d.push(line.d);
        t.push(line.t);
        e.push(line.e);
        n.push(line.n);
      }
    }
    verses += n.length;
    const json = JSON.stringify({ d: d.join('\n'), t: t.join('\n'), e: e.join('\n'), c, n: n.join('\n') });
    bytes += Buffer.byteLength(json);
    writeFileSync(join(dir, `${entry.id}.json`), json);
    ids.push(entry.id);
  }

  // The Ashtavakra Gita has its own reader and data (scripts/build-ashtavakra.mjs), outside the catalog.
  const ashtavakra = join(OUT, 'ashtavakra');
  if (existsSync(join(ashtavakra, 'meta.json'))) {
    const meta = JSON.parse(readFileSync(join(ashtavakra, 'meta.json'), 'utf8'));
    const d = [];
    const t = [];
    const e = [];
    const n = [];
    const c = [];
    for (const m of meta) {
      const p = join(ashtavakra, `ch-${m.number}.json`);
      if (!existsSync(p)) continue;
      const ch = JSON.parse(readFileSync(p, 'utf8'));
      c.push([ch.number, ch.verses.length]);
      for (const v of ch.verses) {
        const line = verseToCorpusLine({
          number: String(v.verseNumber).split('.').slice(1).join('.') || v.verseNumber,
          sanskrit: v.sanskrit,
          hindi: v.literalHindiMeaning,
          transliteration: v.iast,
          translation: v.englishTranslation,
        });
        d.push(line.d);
        t.push(line.t);
        e.push(line.e);
        n.push(line.n);
      }
    }
    if (n.length) {
      verses += n.length;
      const json = JSON.stringify({ d: d.join('\n'), t: t.join('\n'), e: e.join('\n'), c, n: n.join('\n') });
      bytes += Buffer.byteLength(json);
      writeFileSync(join(dir, 'ashtavakra.json'), json);
      ids.push('ashtavakra');
    }
  }

  const loaders = [
    '// Generated by scripts/build-search-index.mjs. Do not edit.',
    "import type { SearchCorpus } from '../types';",
    '',
    'export const SEARCH_LOADERS: Record<string, () => SearchCorpus> = {',
    ...ids.map((id) => `  ${JSON.stringify(id)}: () => require('./search/${id}.json') as SearchCorpus,`),
    '};',
    '',
  ].join('\n');
  writeFileSync(join(OUT, 'search-loaders.ts'), loaders);
  console.log(`[search] indexed ${verses.toLocaleString('en-US')} verses in ${ids.length} books (${(bytes / 1024 / 1024).toFixed(1)} MB)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildSearchIndex();
}
